#define IPU4P_REG_ISYS_SIP1_IRQ_CTRL_STATUS		0x6ed08
#define IPU4P_REG_ISYS_SIP0_IRQ_CTRL_CLEAR		0x66d0c
#define IPU4P_REG_ISYS_SIP1_IRQ_CTRL_CLEAR		0x6ed0c
#define IPU4P_REG_ISYS_CSI_IRQ_CTRL_BASE(p)		\
	({ typeof(p) __p = (p); \
		__p > 0 ? (0x6cb00 + 0x800 * (__p - 1)) : (0x66300); })
#define IPU4P_REG_ISYS_CSI_IRQ_CTRL0_BASE(p)		\
	({ typeof(p) __p = (p); \
		__p > 0 ? (0x6cc00 + 0x800 * (__p - 1)) : (0x66400); })

