/*
 * IPU4P csi2 interrupt fan-in: 5 rx ports feed two SIP irq controllers.
 * UNISPART bit 0x8 = SIP0 (port 0), bit 0x10 = SIP1 (ports 1..4).
 */
#define IPU4P_ISYS_UNISPART_IRQ_CSI2(port)		\
	((port) > 0 ? 0x10 : 0x8)
#define IPU4P_REG_ISYS_SIP0_IRQ_CTRL_BASE		0x66d00
#define IPU4P_REG_ISYS_SIP1_IRQ_CTRL_BASE		0x6ed00
